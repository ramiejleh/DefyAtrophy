import assert from "node:assert/strict";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { assemble, build, untypeableReason } from "../../line-by-line/lib/build.js";
import { splitContent } from "../../line-by-line/lib/session.js";
import { dirSource } from "../../line-by-line/lib/sources.js";
import { validate } from "../../line-by-line/lib/validate.js";
import { author, makeRepo, makeSolution, startServer } from "./helpers.js";

const reason = (path, content = "export const x = 1;\n") => {
  const buf = Buffer.from(content);
  return untypeableReason(path, buf, splitContent(content));
};

test("files nobody would type are skipped, with a reason", () => {
  for (const [path, why] of [
    ["public/logo.svg", "asset"],
    ["src/fonts/Inter.woff2", "asset"],
    ["docs/guide.pdf", "asset"],
    ["bun.lock", "lockfile"],
    ["Podfile.lock", "lockfile"],
    ["fixtures/users.csv", "data file"],
    ["src/__snapshots__/app.test.ts.snap", "generated"],
    ["tsconfig.tsbuildinfo", "generated"],
    ["next-env.d.ts", "generated"],
    ["api/user_pb2.py", "generated"],
    ["ios/App.xcodeproj/project.pbxproj", "generated"],
    ["gradlew", "generated"],
  ]) assert.equal(reason(path), why, path);
  assert.equal(reason("src/client.ts", "// Code generated by openapi-gen. DO NOT EDIT.\nexport {};\n"), "generated");
  assert.equal(reason("src/schema.ts", "/* @generated */\nexport {};\n"), "generated");
});

test("hand-written code is still typed", () => {
  for (const path of ["src/app.ts", "package.json", "tsconfig.json", "vite.config.ts", "Dockerfile", "README.md", "src/icons.tsx"]) {
    assert.equal(reason(path), null, path);
  }
  // mentioning generation in a comment doesn't make a file generated
  assert.equal(reason("src/token.ts", "// Checks tokens generated by the auth server.\nexport {};\n"), null);
});

test("skipped additions and deletions are applied when the step is done, and Claude can skip more", async () => {
  const project = makeRepo({ "src/app.ts": "export const app = 1;\n", "old.svg": "<svg/>\n", "src/api.ts": "export {};\n" });
  const solution = makeSolution(project, {
    "src/app.ts": "export const app = 2;\n",
    "old.svg": null,
    "public/icon.svg": '<svg xmlns="http://www.w3.org/2000/svg"><path d="M0 0h1"/></svg>\n',
    "bun.lock": "{}\n",
    "src/api.ts": "export const getUser = () => fetch('/user');\n",
  });
  const out = join(project, ".line-by-line", "skip");
  const built = build({ mode: "type", from: dirSource(project), to: dirSource(solution), projectDir: project, out, task: "t" });
  assert.deepEqual(built.skipped.map((a) => [a.path, a.action, a.reason]), [
    ["bun.lock", "write", "lockfile"],
    ["old.svg", "delete", "asset"],
    ["public/icon.svg", "write", "asset"],
  ]);

  author(out);
  // Claude decides src/api.ts is a generated client too
  const plan = JSON.parse(readFileSync(join(out, "steps.json"), "utf8"));
  plan.steps[0].files = plan.steps[0].files.filter((f) => f.path !== "src/api.ts");
  plan.steps[0].autoApplied.push({ path: "src/api.ts", reason: "generated client" });
  writeFileSync(join(out, "steps.json"), JSON.stringify(plan));
  assert.deepEqual(assemble(out).errors, []);
  assert.deepEqual(validate(out).errors, []);

  const session = JSON.parse(readFileSync(join(out, "session.json"), "utf8"));
  assert.deepEqual(session.steps[0].files.map((f) => f.path), ["src/app.ts"]);
  assert.deepEqual(
    session.steps[0].autoApplied.map((a) => [a.path, a.reason]).sort(),
    [["bun.lock", "lockfile"], ["old.svg", "asset"], ["public/icon.svg", "asset"], ["src/api.ts", "generated client"]],
  );

  const srv = await startServer(out, project);
  try {
    assert.equal((await srv.call("POST", "/api/file", { path: "src/app.ts" })).status, 200);
    assert.equal((await srv.call("POST", "/api/step-done", { stepId: session.steps[0].id })).status, 200);
    for (const path of ["src/app.ts", "public/icon.svg", "bun.lock", "src/api.ts"]) {
      assert.ok(readFileSync(join(project, path)).equals(readFileSync(join(solution, path))), path);
    }
    assert.equal(existsSync(join(project, "old.svg")), false, "the asset deletion is applied");
  } finally {
    await srv.close();
  }
});

test("skipping a file needs a reason, and it can't be typed too", () => {
  const project = makeRepo({ "a.ts": "1\n", "b.ts": "1\n" });
  const solution = makeSolution(project, { "a.ts": "2\n", "b.ts": "2\n" });
  const out = join(project, ".line-by-line", "bad");
  build({ mode: "type", from: dirSource(project), to: dirSource(solution), projectDir: project, out, task: "t" });
  author(out);
  const plan = JSON.parse(readFileSync(join(out, "steps.json"), "utf8"));
  plan.steps[0].autoApplied = ["a.ts", { path: "b.ts", reason: "generated" }];
  writeFileSync(join(out, "steps.json"), JSON.stringify(plan));
  const { errors } = assemble(out);
  assert.ok(errors.some((e) => e.includes("a.ts needs a reason")), errors.join("\n"));
  assert.ok(errors.some((e) => e.includes("b.ts is both typed")), errors.join("\n"));
});
